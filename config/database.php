<?php
/**
 * CORELBASE PRIVATE LIMITED — PDO DATABASE CONNECTION MANAGER
 * -----------------------------------------------------------------------------
 * Provides singleton PDO connection with prepared statements, strict error
 * handling, and safe server-side error logging.
 */

declare(strict_types=1);

require_once __DIR__ . '/config.php';

class Database
{
    private static ?PDO $instance = null;

    /**
     * Get active PDO connection instance.
     *
     * @throws RuntimeException if database connection fails
     */
    public static function getConnection(): PDO
    {
        if (self::$instance !== null) {
            return self::$instance;
        }

        // Load dynamic config override generated by /install/ if it exists
        $localEnvFile = __DIR__ . '/env.local.php';
        if (file_exists($localEnvFile)) {
            require_once $localEnvFile;
        }

        $host = defined('LOCAL_DB_HOST') ? LOCAL_DB_HOST : DB_HOST;
        $port = defined('LOCAL_DB_PORT') ? LOCAL_DB_PORT : DB_PORT;
        $name = defined('LOCAL_DB_NAME') ? LOCAL_DB_NAME : DB_NAME;
        $user = defined('LOCAL_DB_USER') ? LOCAL_DB_USER : DB_USER;
        $pass = defined('LOCAL_DB_PASS') ? LOCAL_DB_PASS : DB_PASS;

        $dsn = sprintf('mysql:host=%s;port=%s;dbname=%s;charset=%s', $host, $port, $name, DB_CHARSET);

        $options = [
            PDO::ATTR_ERRMODE            => PDO::ERRMODE_EXCEPTION,
            PDO::ATTR_DEFAULT_FETCH_MODE => PDO::FETCH_ASSOC,
            PDO::ATTR_EMULATE_PREPARES   => false,
            PDO::MYSQL_ATTR_INIT_COMMAND => "SET NAMES utf8mb4 COLLATE utf8mb4_unicode_ci, time_zone = '+00:00'",
        ];

        try {
            self::$instance = new PDO($dsn, $user, $pass, $options);
            return self::$instance;
        } catch (PDOException $e) {
            self::logError('Database connection error: ' . $e->getMessage());
            throw new RuntimeException('Database service is temporarily unavailable.');
        }
    }

    /**
     * Check if database is configured and reachable without throwing unhandled errors.
     */
    public static function isAvailable(): bool
    {
        try {
            self::getConnection();
            return true;
        } catch (Throwable $e) {
            return false;
        }
    }

    /**
     * Log technical database errors server-side without exposing details to users.
     */
    public static function logError(string $message): void
    {
        $logDir = CB_LOGS_PATH;
        if (!is_dir($logDir)) {
            @mkdir($logDir, 0750, true);
        }
        $logFile = $logDir . '/error_' . date('Y-m-d') . '.log';
        $entry = sprintf("[%s] [IP:%s] %s\n", date('Y-m-d H:i:s'), $_SERVER['REMOTE_ADDR'] ?? 'CLI', $message);
        @file_put_contents($logFile, $entry, FILE_APPEND | LOCK_EX);
    }
}
