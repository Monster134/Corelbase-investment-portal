// Helper to connect using config/env.local.php
function getInstallerPdo(): PDO
{
    $envFile = CB_CONFIG_PATH . '/env.local.php';
    if (file_exists($envFile)) {
        require_once $envFile;
    }
    $host = defined('LOCAL_DB_HOST') ? LOCAL_DB_HOST : DB_HOST;
    $port = defined('LOCAL_DB_PORT') ? LOCAL_DB_PORT : DB_PORT;
    $name = defined('LOCAL_DB_NAME') ? LOCAL_DB_NAME : DB_NAME;
    $user = defined('LOCAL_DB_USER') ? LOCAL_DB_USER : DB_USER;
    $pass = defined('LOCAL_DB_PASS') ? LOCAL_DB_PASS : DB_PASS;

    $dsn = "mysql:host={$host};port={$port};dbname={$name};charset=utf8mb4";
    return new PDO($dsn, $user, $pass, [
        PDO::ATTR_ERRMODE            => PDO::ERRMODE_EXCEPTION,
        PDO::ATTR_DEFAULT_FETCH_MODE => PDO::FETCH_ASSOC,
    ]);
}

